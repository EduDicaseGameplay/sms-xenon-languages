#!/usr/bin/env python3
"""Carve the texture codecs out of platform/gx/src/gx_texture.cpp for the Xbox 360 build.

usage: xcodec.py REPO OUT.cpp

gx_texture.cpp holds the GameCube texture decoders (decodeTexture, texLevelBytes) and the
EFB copy encoders (copyLayout, encodeTexture) next to its GL texture cache. The decoders and
encoders touch no GL, so the Xenos back end (xenon/gx) compiles them unchanged: everything up
to the cache, the arbitrary-mip test (mipLevelDiff), and the encoder block up to the GL
samplers, without the GL headers. Fails if a
marker moved, rather than compiling the wrong lines."""
import sys

repo, out = sys.argv[1], sys.argv[2]
lines = open(repo + '/platform/gx/src/gx_texture.cpp').read().split('\n')

def at(prefix, start=0):
    for i in range(start, len(lines)):
        if lines[i].startswith(prefix):
            return i
    sys.exit('xcodec: no line starting %r in gx_texture.cpp' % prefix)

cache = at('// ------------------------------------------------------------------ cache')
mip = at('// How far a decoded mip level', cache)
mip_end = at('struct CopyEntry', mip)
enc = at('// Memory layout (texture format) an EFB copy', cache)
smp = at('// GX sampler state', enc)
head = [l.replace('"gx_internal.h"', '"../../platform/gx/src/gx_internal.h"') for l in lines[:cache]
        if l not in ('#include "gl_funcs.h"', '#include "gx_glcache.h"')]
# the arbitrary-mip test too (gx_texture.cpp's cache uses it), visible to the Xenos cache
mips = [l.replace('static float mipLevelDiff', 'float mipLevelDiff')
         .replace('static const float kArbitraryMipThreshold', 'extern const float kArbitraryMipThreshold')
        for l in lines[mip:mip_end]]
body = head + mips + lines[enc:smp] + ['}  // namespace gx', '']
open(out, 'w').write('// Generated by xenon/tools/xcodec.py from platform/gx/src/gx_texture.cpp: do not edit.\n'
                     + '\n'.join(body))
